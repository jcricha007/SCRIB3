"""Cold pen plotting in calibrated P1S/H2S nozzle coordinates."""

from dataclasses import dataclass
from math import dist, isfinite
from pathlib import Path
from .gcode import write_program
from .board import Board
from .motion_profile import START_HOLD_SECONDS

PRINTERS = {"P1S": ("C12", 256, 256), "H2S": ("O1S", 340, 320)}
P1S_FINISH_HOLD_SECONDS = 10


@dataclass(frozen=True)
class Holder:
    printer: str
    offset_x: float
    offset_y: float
    contact_z: float
    lift_z: float
    left: float = 5
    front: float = 30
    right: float = 5
    back: float = 5
    draw_feed: float = 1500
    travel_feed: float = 1500

    def reach(self):
        if self.printer not in PRINTERS:
            raise ValueError("Choose P1S or H2S.")
        if any(
            type(v) not in (int, float) or not isfinite(v)
            for k, v in vars(self).items()
            if k != "printer"
        ):
            raise ValueError("Calibration must contain finite numbers.")
        if not (0 <= self.contact_z < self.lift_z <= 200
                and round(self.contact_z, 3) < round(self.lift_z, 3)):
            raise ValueError("Lift Z must exceed contact Z at output precision.")
        if not all(1 <= v <= 18000 for v in (self.draw_feed, self.travel_feed)):
            raise ValueError("Feeds must be 1 to 18000 mm/min.")
        if min(self.left, self.front, self.right, self.back) < 0:
            raise ValueError("Clearances must be nonnegative.")
        if self.printer == "P1S" and self.left < 18 and self.front < 28:
            raise ValueError(
                "P1S front-left exclusion requires 18 mm left or 28 mm front clearance."
            )
        _, w, h = PRINTERS[self.printer]
        rect = (
            max(0, self.left + self.offset_x),
            max(0, self.front + self.offset_y),
            min(w, w - self.right + self.offset_x),
            min(h, h - self.back + self.offset_y),
        )
        if rect[0] >= rect[2] or rect[1] >= rect[3]:
            raise ValueError("Holder leaves no reachable paper area.")
        return rect


@dataclass(frozen=True)
class PrinterPlan:
    holder: Holder
    passes: tuple
    scale: float
    width: float
    height: float
    seconds: float
    dry: bool
    paper_origin: tuple

    def gcode(self):
        h = self.holder
        p1s = h.printer == "P1S"
        lines = [
            "; HEADER_BLOCK_START",
            "; generated by SCRIB3",
            f"; printer_model = Bambu Lab {h.printer}",
            "; total layer number: 1",
            "; HEADER_BLOCK_END",
            "; Home with pen and any obstructing holder removed.",
            "G21",
            "G90",
            "M104 S0",
            "M140 S0",
            "G28",
            "G90",
            f"G1 Z{h.lift_z:.3f} F600",
            "; Install calibrated holder and pen at the pause.",
            "M400",
            "M400 U1",
            "; CHANGE_LAYER",
            f"; Z_HEIGHT: {h.contact_z:.3f}",
            "; FEATURE: Custom",
        ]
        def move_pen_z(height):
            lines.append(f"G1 Z{height:.3f} F600")
            if p1s:
                lines.append("M400")

        for index, (color, paths) in enumerate(self.passes):
            lines.append(f"; Pen {index+1}: {color}")
            if index:
                lines.extend(["M400", "M400 U1"])
            lines.append("G90")
            move_pen_z(h.lift_z)
            for n, stroke in enumerate(paths):
                x, y = stroke[0]
                lines.append(f"G1 X{x:.3f} Y{y:.3f} F{h.travel_feed:.0f}")
                if index == 0 and n == 0:
                    lines.extend(["M400", f"G4 P{START_HOLD_SECONDS * 1000}" if p1s else "G4 P5000"])
                elif p1s and not self.dry:
                    lines.append("M400")
                if not self.dry:
                    move_pen_z(h.contact_z)
                lines.extend(f"G1 X{x:.3f} Y{y:.3f} F{h.draw_feed:.0f}" for x, y in stroke[1:])
                if not self.dry:
                    if p1s:
                        lines.append("M400")
                    move_pen_z(h.lift_z)
        if self.dry or not p1s:
            lines.append("M400")
        if p1s:
            # A user pause (M400 U1) can park the head. A timed dwell leaves XY in place.
            lines.append(f"G4 P{P1S_FINISH_HOLD_SECONDS * 1000}")
        lines.append("; SCRIB3 complete; pen raised.")
        return "\n".join(lines) + "\n"

    def export(self, path):
        if Path(path).suffix.lower() == ".3mf":
            from .sliced_plate import export_plate

            export_plate(Path(path), self)
        else:
            write_program(Path(path), self.gcode())


def order_paths(paths, start=(0, 0)):
    """Nearest endpoint traversal with exact path geometry retained."""
    from scipy.spatial import cKDTree

    ends = [p for s in paths for p in (s[0], s[-1])]
    tree = cKDTree(ends)
    pending = set(range(len(paths)))
    output = []
    while pending:
        k = min(16, len(ends))
        while True:
            _, ids = tree.query(start, k=k)
            candidates = [
                int(i) for i in __import__("numpy").atleast_1d(ids) if int(i) // 2 in pending
            ]
            if candidates:
                endpoint = candidates[0]
                break
            k = min(len(ends), k * 2)
        i = endpoint // 2
        stroke = tuple(reversed(paths[i])) if endpoint % 2 else paths[i]
        output.append(stroke)
        pending.remove(i)
        start = stroke[-1]
    return tuple(output)


def plan_printer(board: Board, holder: Holder, *, fit=False, dry=True, optimize=True, area=None):
    board.checked()
    x0, y0, x1, y1 = holder.reach()
    if area is not None:
        a,b,c,d = area
        if not (x0 <= a < c <= x1 and y0 <= b < d <= y1):
            raise ValueError("Paper placement exceeds calibrated reach.")
        x0,y0,x1,y1 = area
    scale = min(1, (x1 - x0) / board.width, (y1 - y0) / board.height)
    if scale < 1 - 1e-9 and not fit:
        raise ValueError(
            "Paper exceeds the calibrated pen area. Enable shrink or choose smaller paper."
        )
    w, h = board.width * scale, board.height * scale
    left = (x0 + x1 - w) / 2 - holder.offset_x
    front = (y0 + y1 - h) / 2 - holder.offset_y
    passes = []
    seconds = START_HOLD_SECONDS + P1S_FINISH_HOLD_SECONDS if holder.printer == "P1S" else 5.0
    previous = None
    for color in board.pens():
        paths, _ = board.plot_layer(color)
        if optimize:
            paths = order_paths(paths)
        converted = []
        for path in paths:
            points = []
            for x, y in path:
                point = round(left + x * scale, 3), round(front + y * scale, 3)
                nx, ny = point
                _, bw, bh = PRINTERS[holder.printer]
                if not (
                    holder.left - 1e-9 <= nx <= bw - holder.right + 1e-9
                    and holder.front - 1e-9 <= ny <= bh - holder.back + 1e-9
                    and -1e-9 <= nx + holder.offset_x <= bw + 1e-9
                    and -1e-9 <= ny + holder.offset_y <= bh + 1e-9
                ):
                    raise ValueError("Rounded point exceeds calibrated travel. Increase clearance.")
                if area is not None and not (x0-1e-9 <= nx+holder.offset_x <= x1+1e-9 and
                                              y0-1e-9 <= ny+holder.offset_y <= y1+1e-9):
                    raise ValueError("Rounded motion crosses the paper or clip boundary. Adjust placement.")
                if not points or points[-1] != point:
                    points.append(point)
            if len(points) < 2:
                raise ValueError(
                    "A stroke disappears at 0.001 mm resolution. Enlarge or remove it before output."
                )
            if previous is not None:
                seconds += 60 * dist(previous, points[0]) / holder.travel_feed
            seconds += 60 * sum(dist(a, b) for a, b in zip(points, points[1:])) / holder.draw_feed
            if not dry:
                seconds += (holder.lift_z - holder.contact_z) / 5
            previous = points[-1]
            converted.append(tuple(points))
        passes.append((color, tuple(converted)))
    if not passes:
        raise ValueError("Add visible artwork.")
    return PrinterPlan(holder, tuple(passes), scale, w, h, seconds, dry, (left+holder.offset_x, front+holder.offset_y))
